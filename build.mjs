/* Compile src/ironset.src.html into the two files GitHub Pages actually serves.

   The app is authored as one file with a <script type="text/babel"> block, which
   is what has made this project fast: change a line, push, it is on the phone a
   minute later with no toolchain in the way. The cost was that every cold start
   downloaded 2.8MB of babel-standalone — five times the app itself — and compiled
   half a megabyte of JSX on the device before anything could be drawn.

   So the authoring stays exactly as it was and the compile moves here. Edit
   src/ironset.src.html, run `node build.mjs`, commit all three. A test in the
   suite rebuilds and compares, so a forgotten build fails like any other bug
   rather than silently shipping a stale app.                                   */
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const Babel = require(process.env.SP
  ? process.env.SP + "/vendor/node_modules/@babel/standalone"
  : "@babel/standalone");

const SRC = new URL("./src/ironset.src.html", import.meta.url);
const html = readFileSync(SRC, "utf8");

const open = html.search(/<script type="text\/babel"[^>]*>/);
if (open < 0) throw new Error("no babel block in src/ironset.src.html");
const bodyAt = html.indexOf(">", open) + 1;
const close = html.lastIndexOf("</script>");
if (close < bodyAt) throw new Error("babel block never closes");

const jsx = html.slice(bodyAt, close);
const { code } = Babel.transform(jsx, {
  presets: [["react", { runtime: "classic" }]],
  // The browsers this ships to all run modern syntax; transpiling further would
  // only make the output bigger and slower for no one's benefit.
  compact: false,
  comments: true,
});

const out = html.slice(0, open)
    .replace(/\n[^\n]*babel-standalone[^\n]*\n/, "\n")
  + '<script src="app.js"></script>'
  + html.slice(close + "</script>".length);

writeFileSync(new URL("./ironset.html", import.meta.url),
  out.replace("<title>", "<!-- Generated by build.mjs from src/ironset.src.html — edit that, not this. -->\n<title>"));
writeFileSync(new URL("./app.js", import.meta.url), code);
console.log(`built: ironset.html ${(out.length / 1024).toFixed(0)}KB + app.js ${(code.length / 1024).toFixed(0)}KB`);
